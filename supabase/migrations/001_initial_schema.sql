begin;

create extension if not exists pgcrypto;

create sequence if not exists public.order_number_seq
  as bigint
  start with 1047
  increment by 1;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Администратором считается пользователь Supabase Auth с
-- app_metadata.role = "admin". app_metadata назначается только на сервере.
create or replace function public.is_admin()
returns boolean
language sql
stable
set search_path = public
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin';
$$;

create table if not exists public.orders (
  id text primary key default gen_random_uuid()::text,
  number bigint not null default nextval('public.order_number_seq'),
  title text not null,
  location text not null default '',
  description text not null default '',
  preferred_deadline text not null default '',
  work_subtotal numeric(14,2) not null default 0 check (work_subtotal >= 0),
  materials_subtotal numeric(14,2) not null default 0 check (materials_subtotal >= 0),
  surcharges numeric(14,2) not null default 0 check (surcharges >= 0),
  calculated_cost numeric(14,2) not null default 0 check (calculated_cost >= 0),
  calculated_total numeric(14,2) not null default 0 check (calculated_total >= 0),
  final_total numeric(14,2) not null default 0 check (final_total >= 0),
  total numeric(14,2) not null default 0 check (total >= 0),
  contractor_payment numeric(14,2) not null default 0 check (contractor_payment >= 0),
  client_price numeric(14,2) not null default 0 check (client_price >= 0),
  owner_expenses numeric(14,2) not null default 0 check (owner_expenses >= 0),
  expected_profit numeric(14,2) not null default 0,
  photos text[] not null default '{}'::text[],
  status text not null default 'draft' check (status in ('draft', 'active', 'closed')),
  is_published boolean not null default false,
  is_manual_total boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_number_unique unique (number),
  constraint orders_publication_state_check check (not is_published or status = 'active')
);

alter sequence public.order_number_seq owned by public.orders.number;

create table if not exists public.order_works (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  work_id text,
  category_id text,
  group_id text,
  title text not null,
  unit text not null default '',
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  quantity numeric(14,3) not null default 0 check (quantity >= 0),
  total_price numeric(14,2) not null default 0 check (total_price >= 0),
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.projects (
  id text primary key default gen_random_uuid()::text,
  client_name text not null default '',
  location text not null default '',
  title text not null,
  description text not null default '',
  deadline text not null default '',
  review text not null default '',
  work_subtotal numeric(14,2) not null default 0 check (work_subtotal >= 0),
  materials_subtotal numeric(14,2) not null default 0 check (materials_subtotal >= 0),
  extra_costs numeric(14,2) not null default 0 check (extra_costs >= 0),
  calculated_total numeric(14,2) not null default 0 check (calculated_total >= 0),
  final_total numeric(14,2) not null default 0 check (final_total >= 0),
  total numeric(14,2) not null default 0 check (total >= 0),
  is_manual_total boolean not null default false,
  is_published boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_works (
  id bigint generated by default as identity primary key,
  project_id text not null references public.projects(id) on delete cascade,
  work_id text,
  category_id text,
  group_id text,
  title text not null,
  unit text not null default '',
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  quantity numeric(14,3) not null default 0 check (quantity >= 0),
  total_price numeric(14,2) not null default 0 check (total_price >= 0),
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_media (
  id bigint generated by default as identity primary key,
  project_id text not null references public.projects(id) on delete cascade,
  stage text not null check (stage in ('before', 'process', 'after')),
  src text not null,
  is_cover boolean not null default false,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_documents (
  id bigint generated by default as identity primary key,
  project_id text not null references public.projects(id) on delete cascade,
  document_type text not null check (document_type in ('contract', 'act', 'additional')),
  name text not null,
  mime_type text not null default 'application/octet-stream',
  src text not null,
  is_public boolean not null default false,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id text primary key default gen_random_uuid()::text,
  client_name text not null,
  location text not null,
  service_title text not null,
  review_text text not null,
  rating smallint not null default 5 check (rating between 1 and 5),
  photos jsonb not null default '[]'::jsonb check (jsonb_typeof(photos) = 'array'),
  order_number text not null default '',
  contact text not null default '',
  consent boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'published', 'rejected')),
  is_published boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reviews_publication_state_check check (is_published = (status = 'published'))
);

create table if not exists public.pricing_overrides (
  id bigint generated by default as identity primary key,
  scope text not null check (scope in ('calculatorWorks', 'turnkey', 'materials', 'serviceItems', 'serviceCategories')),
  item_id text not null,
  price numeric(14,2) not null check (price >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pricing_overrides_scope_item_unique unique (scope, item_id)
);

create unique index if not exists project_media_one_cover_per_project_idx
