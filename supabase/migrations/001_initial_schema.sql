-- Безопасные публичные представления. Они не включают client_price,
-- owner_expenses, expected_profit и контактные/модерационные поля отзывов.
create or replace view public.published_orders
with (security_invoker = true)
as
select
  o.id,
  o.number,
  o.title,
  o.location,
  o.description,
  o.preferred_deadline,
  o.contractor_payment,
  o.photos,
  o.created_at,
  o.updated_at,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'work_id', ow.work_id,
        'title', ow.title,
        'unit', ow.unit,
        'quantity', ow.quantity
      ) order by ow.sort_order, ow.id
    )
    from public.order_works ow
    where ow.order_id = o.id
  ), '[]'::jsonb) as selected_works
from public.orders o
where o.is_published and o.status = 'active';

create or replace view public.published_projects
with (security_invoker = true)
as
select
  p.id,
  p.client_name,
  p.location,
  p.title,
  p.description,
  p.deadline,
  p.final_total,
  p.total,
  p.created_at,
  p.updated_at,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'work_id', pw.work_id,
        'title', pw.title,
        'unit', pw.unit,
        'unit_price', pw.unit_price,
        'quantity', pw.quantity,
        'total_price', pw.total_price
      ) order by pw.sort_order, pw.id
    )
    from public.project_works pw
    where pw.project_id = p.id
  ), '[]'::jsonb) as works,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'src', pm.src,
        'stage', pm.stage,
        'is_cover', pm.is_cover,
        'sort_order', pm.sort_order
      ) order by pm.sort_order, pm.id
    )
    from public.project_media pm
    where pm.project_id = p.id
  ), '[]'::jsonb) as media,
  coalesce((
    select jsonb_agg(
      jsonb_build_object(
        'name', pd.name,
        'type', pd.mime_type,
        'src', pd.src,
        'document_type', pd.document_type
      ) order by pd.sort_order, pd.id
    )
    from public.project_documents pd
    where pd.project_id = p.id and pd.is_public
  ), '[]'::jsonb) as documents
from public.projects p
where p.is_published;

create or replace view public.published_reviews
with (security_invoker = true)
as
select
  id,
  client_name,
  location,
  service_title,
  review_text,
  rating,
  photos,
  created_at,
  updated_at
from public.reviews
where is_published and status = 'published';

