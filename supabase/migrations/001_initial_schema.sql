-- Публичное чтение разрешено только для опубликованных записей.
create policy "anon reads published orders"
on public.orders for select to anon
using (is_published and status = 'active');

create policy "anon reads works of published orders"
on public.order_works for select to anon
using (exists (
  select 1 from public.orders
  where orders.id = order_works.order_id
    and orders.is_published
    and orders.status = 'active'
));

create policy "anon reads published projects"
on public.projects for select to anon
using (is_published);

create policy "anon reads works of published projects"
on public.project_works for select to anon
using (exists (
  select 1 from public.projects
  where projects.id = project_works.project_id
    and projects.is_published
));

create policy "anon reads media of published projects"
on public.project_media for select to anon
using (exists (
  select 1 from public.projects
  where projects.id = project_media.project_id
    and projects.is_published
));

create policy "anon reads public documents of published projects"
on public.project_documents for select to anon
using (is_public and exists (
  select 1 from public.projects
  where projects.id = project_documents.project_id
    and projects.is_published
));

create policy "anon reads published reviews"
on public.reviews for select to anon
using (is_published and status = 'published');

-- Аноним может отправить только новый отзыв на модерацию.
-- Права на INSERT ниже не позволяют передать status/is_published/is_demo.
create policy "anon submits pending reviews"
on public.reviews for insert to anon
with check (
  status = 'pending'
  and not is_published
  and not is_demo
  and consent
  and char_length(btrim(client_name)) between 1 and 120
  and char_length(btrim(location)) between 1 and 240
  and char_length(btrim(service_title)) between 1 and 240
  and char_length(btrim(review_text)) between 1 and 5000
  and char_length(contact) <= 500
  and jsonb_array_length(photos) <= 10
);

