const makeItems = (categoryId, rows) => rows
  .filter(([name]) => !existingNames.has(normalizeName(name)))
  .map(([name, unit, mount], index) => ({
    id: `ramil_${categoryId}_${String(index + 1).padStart(3, '0')}`,
    name,
    unit,
    mount,
    dismount: 0,
    materials: [],
  }));

export const CALC_CATEGORIES = BASE_CALC_CATEGORIES.map((category) => {
  const rows = RAMIL_ADDITIONS[category.id];
  if (!rows) return category;

  const items = makeItems(category.id, rows);
  if (!items.length) return category;

  return {
    ...category,
    groups: [
      ...category.groups,
      {
        id: `ramil_${category.id}_20260907`,
        name: 'Дополнительные работы',
        items,
      },
    ],
  };
});
